const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { createHash } = require('node:crypto');
const { auditRelease } = require('./audit-release.cjs');
const root = path.resolve(__dirname, '..');
const { version } = auditRelease(root);
const bundle = path.join(root, 'outputs', 'CourseBridge-Windows');
if (!fs.existsSync(path.join(bundle, 'CourseBridge.exe'))) throw new Error('请先运行 npm run package:win');
if (JSON.parse(fs.readFileSync(path.join(bundle, 'resources/app/package.json'), 'utf8')).version !== version) throw new Error('发行目录版本与源码不一致，请重新打包');
const config = JSON.parse(fs.readFileSync(path.join(root, 'packaging', 'builder.json'), 'utf8'));
config.directories.output = path.join(root, 'outputs', 'installers');
config.win.icon = path.join(root, 'desktop', 'assets', 'app.ico');
fs.mkdirSync(path.join(root, 'work'), { recursive: true });
const configFile = path.join(root, 'work', 'builder.json');
fs.writeFileSync(configFile, JSON.stringify(config, null, 2));
const cli = path.join(root, 'packaging', 'node_modules', 'electron-builder', 'cli.js');
if (!fs.existsSync(cli)) throw new Error('请先运行 npm ci --prefix packaging');
execFileSync(process.execPath, [cli, '--win', 'nsis', '--x64', '--prepackaged', bundle, '--config', configFile, '--publish', 'never'], { cwd: root, windowsHide: true, stdio: 'inherit' });
const installer = path.join(config.directories.output, `CourseBridge-${version}-Setup.exe`);
const hash = createHash('sha256').update(fs.readFileSync(installer)).digest('hex');
fs.writeFileSync(path.join(config.directories.output, 'SHA256SUMS.txt'), `${hash}  ${path.basename(installer)}\n`);
console.log(installer);
