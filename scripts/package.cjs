const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { auditRelease } = require('./audit-release.cjs');
const root = path.join(__dirname, '..');
const dest = path.join(root, 'outputs', 'CourseBridge-Windows');
const runtime = path.join(root, 'node_modules', 'electron', 'dist');
auditRelease(root);
if (!fs.existsSync(path.join(runtime, 'electron.exe'))) throw new Error('请先安装 Electron 的 Windows 运行时');
if (fs.existsSync(dest)) throw new Error('输出目录已经存在，请先将旧版本另存后重新打包');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.cpSync(runtime, dest, { recursive: true });
fs.copyFileSync(path.join(runtime, 'LICENSE'), path.join(dest, 'LICENSE.electron.txt'));
fs.renameSync(path.join(dest, 'electron.exe'), path.join(dest, 'CourseBridge.exe'));
const appDest = path.join(dest, 'resources', 'app');
fs.mkdirSync(appDest, { recursive: true });
fs.mkdirSync(path.join(appDest, 'node_modules'), { recursive: true });
fs.cpSync(path.join(root, 'node_modules', 'playwright-core'), path.join(appDest, 'node_modules', 'playwright-core'), { recursive: true });
for (const name of ['desktop', 'extension', 'examples', 'docs', 'LICENSE', 'README.md', 'THIRD_PARTY_NOTICES.md', 'CHANGELOG.md', 'CONTRIBUTING.md']) fs.cpSync(path.join(root, name), path.join(appDest, name), { recursive: true });
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
delete manifest.devDependencies;
delete manifest.scripts;
fs.writeFileSync(path.join(appDest, 'package.json'), JSON.stringify(manifest, null, 2));
fs.cpSync(path.join(root, 'extension'), path.join(dest, 'extension'), { recursive: true });
fs.cpSync(path.join(root, 'examples'), path.join(dest, 'examples'), { recursive: true });
fs.copyFileSync(path.join(root, 'README.md'), path.join(dest, '使用说明.md'));
fs.copyFileSync(path.join(root, 'LICENSE'), path.join(dest, 'LICENSE-CourseBridge'));
for (const name of ['README.md', 'THIRD_PARTY_NOTICES.md', 'CHANGELOG.md']) fs.copyFileSync(path.join(root, name), path.join(dest, name));
fs.cpSync(path.join(root, 'docs'), path.join(dest, 'docs'), { recursive: true });
execFileSync('powershell.exe', ['-NoProfile', '-File', path.join(root,'scripts','set-exe-icon.ps1'), '-ExePath', path.join(dest,'CourseBridge.exe'), '-IconPath', path.join(root,'desktop','assets','app.ico')], {stdio:'inherit',windowsHide:true});
console.log(dest);
